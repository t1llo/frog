    func testOptInBoundsDuplicatesAndDisableClearsMemory() async throws {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        pasteboard.setString("Before opt-in", forType: .string)
        let history = ClipboardHistoryStore(pasteboard: pasteboard)
        await history.poll()
        XCTAssertTrue(history.entries.isEmpty)
        history.configure(enabled: true, automaticallyPoll: false)
        await history.poll()
        XCTAssertTrue(history.entries.isEmpty)
        for index in 0..<7 {
            pasteboard.clearContents(); pasteboard.setString("Entry \(index)", forType: .string)
            await history.poll()
        }
        XCTAssertEqual(history.entries.map(\.text), ["Entry 6", "Entry 5", "Entry 4", "Entry 3", "Entry 2"])
        pasteboard.clearContents(); pasteboard.setString("Entry 3", forType: .string)
        await history.poll()
        XCTAssertEqual(history.entries.map(\.text), ["Entry 3", "Entry 6", "Entry 5", "Entry 4", "Entry 2"])
        history.configure(enabled: false)
        XCTAssertTrue(history.entries.isEmpty)
        history.configure(enabled: true, automaticallyPoll: false)
        await history.poll()
        XCTAssertTrue(history.entries.isEmpty)
    }

    func testFormattedAndUnformattedDelivery() async throws {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        let history = ClipboardHistoryStore(pasteboard: pasteboard)
        history.configure(enabled: true, automaticallyPoll: false)
        let rtf = Data("{\\rtf1\\ansi\\b Bold text}".utf8)
        let item = NSPasteboardItem()
        item.setString("Bold text", forType: .string); item.setData(rtf, forType: .rtf)
        item.setData(Data([1, 2, 3]), forType: .png)
        pasteboard.clearContents(); pasteboard.writeObjects([item])
        await history.poll()
        let entry = try XCTUnwrap(history.entries.first)
        XCTAssertEqual(entry.formatting, [NSPasteboard.PasteboardType.rtf.rawValue: rtf])
        XCTAssertTrue(entry.write(to: pasteboard, plainText: false))
        XCTAssertEqual(pasteboard.data(forType: .rtf), rtf)
        XCTAssertNil(pasteboard.data(forType: .png))
        XCTAssertTrue(entry.write(to: pasteboard, plainText: true))
        XCTAssertEqual(pasteboard.string(forType: .string), "Bold text")
        XCTAssertNil(pasteboard.data(forType: .rtf))
    }

    func testOversizedAndInternalCopiesAreExcludedButGeneratedTextIsIncluded() async throws {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        let gate = ClipboardHistoryCaptureGate()
        let history = ClipboardHistoryStore(pasteboard: pasteboard, gate: gate)
        history.configure(enabled: true, automaticallyPoll: false)
        for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            let item = NSPasteboardItem()
            item.setString("Sensitive text", forType: .string)
            item.setString("", forType: NSPasteboard.PasteboardType(marker))
            pasteboard.clearContents(); pasteboard.writeObjects([item]); await history.poll()
        }
        XCTAssertEqual(history.entries.map(\.text), ["Sensitive text"])
        history.clear()
        pasteboard.clearContents(); pasteboard.setString(String(repeating: "x", count: 512 * 1024 + 1), forType: .string)
        await history.poll()
        gate.begin()
        pasteboard.clearContents(); pasteboard.setString("Internal selection", forType: .string)
        await history.poll()
        pasteboard.clearContents(); pasteboard.setString("Restored clipboard", forType: .string)
        gate.end(pasteboard: pasteboard)
        await history.poll()
        XCTAssertTrue(history.entries.isEmpty)
        pasteboard.clearContents(); pasteboard.setString("User copy", forType: .string)
        await history.poll()
        XCTAssertEqual(history.entries.map(\.text), ["User copy"])
        history.clear(); await history.poll()
        XCTAssertTrue(history.entries.isEmpty)
        history.configure(enabled: false)
    }

