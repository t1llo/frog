            suspended.resume(); await finished.value
            XCTAssertEqual(target.requests, 0, removal)
            XCTAssertEqual(pasteboard.string(forType: .string), "Unchanged", removal)
            XCTAssertFalse(history.copy(entry), removal)
            XCTAssertEqual(pasteboard.string(forType: .string), "Unchanged", removal)
        }
    }
