private final class CountingNotificationCenter: NotificationCenter, @unchecked Sendable {
    private let lock = NSLock()
    private var tokens = Set<ObjectIdentifier>()
    var observerCount: Int { lock.lock(); defer { lock.unlock() }; return tokens.count }
    override func addObserver(forName name: NSNotification.Name?, object obj: Any?, queue: OperationQueue?,
                              using block: @Sendable @escaping (Notification) -> Void) -> NSObjectProtocol {
        let token = super.addObserver(forName: name, object: obj, queue: queue, using: block)
        lock.lock(); tokens.insert(ObjectIdentifier(token)); lock.unlock()
        return token
    }
    override func removeObserver(_ observer: Any) {
        lock.lock(); tokens.remove(ObjectIdentifier(observer as AnyObject)); lock.unlock()
        super.removeObserver(observer)
    }
}

