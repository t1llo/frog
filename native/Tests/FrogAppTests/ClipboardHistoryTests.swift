    func testPasteWaitsForReleaseAndCannotDeliverAfterDisable() async throws {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        pasteboard.setString("Unchanged", forType: .string)
        let target = TestPasteTarget()
        let entry = ClipboardHistoryEntry(text: "Chosen")
        var current = true
        do {
            try await ClipboardHistoryDelivery.paste(entry, plainText: true, pasteboard: pasteboard, target: target,
