    func testRemovalDuringPendingPasteInvalidatesDeliveryAndStaleCopies() async throws {
        _ = NSApplication.shared
        for removal in ["clear", "evict", "replace"] {
            let pasteboard = NSPasteboard.withUniqueName()
            defer { pasteboard.releaseGlobally() }
            let history = ClipboardHistoryStore(pasteboard: pasteboard)
            history.configure(enabled: true, automaticallyPoll: false)
            pasteboard.clearContents(); pasteboard.setString("Chosen private text", forType: .string); await history.poll()
            let entry = try XCTUnwrap(history.entries.first)
            pasteboard.clearContents(); pasteboard.setString("Unchanged", forType: .string)
            var release: CheckedContinuation<Void, Never>?
            let target = TestPasteTarget()
            let controller = ClipboardHistoryController(pasteboard: pasteboard, history: history, captureTarget: { target },
                waitForRelease: { await withCheckedContinuation { release = $0 } }, activationNotifications: NotificationCenter())
            defer { controller.stop() }
            controller.show()
            let panel = try XCTUnwrap(NSApplication.shared.windows.first { $0.isVisible && $0.title == "Clipboard history" })
            try await sendKey(36, to: panel)
            let finished = Task { await controller.waitForDelivery() }
            for _ in 0..<100 where release == nil { await Task.yield() }
            let suspended = try XCTUnwrap(release, "Delivery must reach the modifier-release wait before removing the item")
            switch removal {
            case "clear": history.clear()
            case "evict":
                for index in 0..<100 {
                    pasteboard.clearContents(); pasteboard.setString("New fixture \(index)", forType: .string); await history.poll()
                }
            default:
                let item = NSPasteboardItem()
                item.setString(entry.text, forType: .string)
