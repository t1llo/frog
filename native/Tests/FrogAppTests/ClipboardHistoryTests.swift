        controller.show(); controller.stop()
        XCTAssertTrue(history.entries.isEmpty)
        XCTAssertFalse(history.enabled)
        XCTAssertFalse(NSApplication.shared.windows.contains { $0.isVisible && $0.title == "Clipboard history" })
